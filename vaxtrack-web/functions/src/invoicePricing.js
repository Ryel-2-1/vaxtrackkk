"use strict";

/**
 * Invoice base pricing, derived from an order's immutable snapshot.
 *
 * Pure: no Firestore, no Functions SDK. Everything that decides what an invoice
 * line COSTS lives here, so it is unit-testable without an emulator, and so
 * there is exactly one implementation of the arithmetic rather than one on each
 * side of the wire.
 *
 * THE AUTHORITY BOUNDARY
 *   Base pricing — item identity, quantity, unitPriceCentavos, lineTotalCentavos,
 *   subtotalCentavos, currency and the price convention (`priceIsVatInclusive`)
 *   — comes from the ORDER's snapshot and from nowhere else; only the VAT rate
 *   comes from pricingConfig.js. The caller cannot supply, override or
 *   influence any of it, and neither can the CURRENT pricing configuration: an
 *   order recorded VAT-exclusive is invoiced VAT-exclusive, forever.
 *
 *   Adjustments — discount, other charges, withholding tax and the VAT
 *   classification — are genuinely the admin's decision, so they ARE accepted
 *   from the caller. They are separate fields that sit alongside the base and
 *   can never overwrite it: a discount reduces the net, it does not restate what
 *   a vial cost.
 *
 * Legacy orders (no pricingVersion) never reach this module. They keep the
 * manual invoice-time pricing they have always had.
 */

const {
  PRICING_VERSION,
  PRICE_CURRENCY,
  PolicyError,
  readProductVatClassification,
} = require("./policy");
const {
  VAT_RATE_PERCENT,
  readPriceConvention,
  splitVatInclusiveCentavos,
  legacyVatOnTopCentavos,
} = require("./pricingConfig");
const { hasPriceAgreement, lineVat, STATUTORY_DISCOUNT_TYPES } = require("./negotiatedPricing");

/** Philippine VAT, from the one pricing configuration (pricingConfig.js). */
const VAT_STANDARD_RATE = VAT_RATE_PERCENT;
const VAT_CLASSIFICATIONS = Object.freeze(["vatable", "vat_exempt", "zero_rated"]);

/**
 * The invoice-level marker for an order whose EVERY item carries a VAT
 * snapshot. Its VAT comes from those items, not from an Admin choice: VATable
 * and VAT-Exempt sales are summed per line, an invoice discount is split
 * between them pro-rata (see allocateDiscountCentavos), and the 12% VAT
 * applies to the discounted VATable sales only — extracted from them for a
 * VAT-inclusive order, added on top for a legacy VAT-exclusive one (the
 * order's own `priceIsVatInclusive`). Orders without item snapshots keep the
 * Admin's invoice-level classification, which must be chosen explicitly.
 */
const ITEMIZED_VAT = "per_item";

/**
 * Free-text fields an admin genuinely owns.
 *
 * An allowlist rather than a denylist: a new field added to the editor must be
 * named here deliberately, so a caller can never smuggle `subtotalCentavos`
 * through as "presentation" simply because nobody thought to forbid it.
 */
const PRESENTATION_FIELDS = Object.freeze([
  "customerName", "registeredName", "customerAddress", "customerContact",
  "customerTin", "customerCode", "shipTo",
  "salesRepName", "salesRepCode",
  "invoiceDate", "saleType", "purchaseOrderNumber", "referenceNumber",
  "companyName", "companyAddress", "companyContact", "companyTin",
  "paymentTerms", "deliveryTerms", "notes", "remarks",
  "processedBy", "packedBy", "deliveredBy", "preparedBy", "checkedBy",
  "approvedBy", "receivedBy", "authorizedRepresentative",
  "customerAcknowledgment", "soloParentId", "bookletInfo",
  "atpNumber", "atpDate", "printerBlock", "accreditationNo", "accreditationDates",
]);

const MAX_PRESENTATION_LENGTH = 500;

/** An order whose prices were generated by the server. Version stamp only. */
function isServerPricedOrder(order) {
  return order?.pricingVersion === PRICING_VERSION;
}

/** A stored money figure: an exactly-representable non-negative integer. */
function readCentavos(value) {
  return (
    typeof value === "number" &&
    Number.isInteger(value) &&
    Number.isSafeInteger(value) &&
    value >= 0
  );
}

function centavosToPesos(centavos) {
  return Math.round(centavos) / 100;
}

/**
 * The invoice's base pricing, computed from the order snapshot.
 *
 * Every figure is RE-DERIVED here and cross-checked against what the order
 * recorded, so a corrupted order document produces a refusal rather than a
 * plausible-looking invoice. Nothing in the returned object came from a caller.
 */
function buildInvoiceBaseFromOrder(order) {
  if (!isServerPricedOrder(order)) {
    throw new PolicyError(
      "order-not-priced",
      "This order has no server price snapshot. It is invoiced through the manual path."
    );
  }
  const orderItems = Array.isArray(order.items) ? order.items : [];
  if (orderItems.length === 0) {
    throw new PolicyError(
      "order-has-no-items",
      "This order has no items to invoice."
    );
  }

  let subtotalCentavos = 0;
  let statutoryDiscountTotalCentavos = 0;
  const agreement = hasPriceAgreement(order);
  const items = orderItems.map((it, index) => {
    const quantity = it?.quantity;
    if (typeof quantity !== "number" || !Number.isInteger(quantity) || quantity <= 0) {
      throw new PolicyError("order-snapshot-invalid", "This order's quantities cannot be invoiced.", {
        line: index,
      });
    }
    if (!readCentavos(it?.unitPriceCentavos) || it.unitPriceCentavos <= 0) {
      throw new PolicyError("order-snapshot-invalid", "This order's prices cannot be invoiced.", {
        line: index,
      });
    }
    // Recomputed, then compared with what the order stored. Trusting the stored
    // line total would let a single tampered field flow straight onto a bill.
    const lineTotalCentavos = quantity * it.unitPriceCentavos;
    if (!Number.isSafeInteger(lineTotalCentavos)) {
      throw new PolicyError("order-snapshot-invalid", "This order's totals are out of range.", {
        line: index,
      });
    }
    if (it.lineTotalCentavos !== lineTotalCentavos) {
      throw new PolicyError(
        "order-snapshot-invalid",
        "This order's line totals do not match its prices and quantities.",
        { line: index }
      );
    }
    subtotalCentavos += lineTotalCentavos;

    // Orders priced under the agreement model carry a statutory discount, a
    // final charged total and a VAT figure PER LINE. Each is re-derived here
    // and compared with what the order stored, exactly like the line total.
    let lineLevel = {};
    if (agreement) {
      const discount = it?.statutoryDiscountCentavos ?? 0;
      const type = it?.statutoryDiscountType ?? null;
      const validDiscount =
        readCentavos(discount) &&
        discount <= lineTotalCentavos &&
        (discount === 0 ? type === null : STATUTORY_DISCOUNT_TYPES.includes(type));
      const finalLineTotalCentavos = lineTotalCentavos - (validDiscount ? discount : 0);
      const vat = lineVat(finalLineTotalCentavos, it?.vatClassification);
      if (
        !validDiscount ||
        it?.finalLineTotalCentavos !== finalLineTotalCentavos ||
        it?.lineVatCentavos !== vat.lineVatCentavos
      ) {
        throw new PolicyError(
          "order-snapshot-invalid",
          "This order's line discounts or VAT do not match its prices.",
          { line: index }
        );
      }
      statutoryDiscountTotalCentavos += discount;
      lineLevel = {
        statutoryDiscountType: type,
        statutoryDiscountCentavos: discount,
        finalLineTotalCentavos,
        lineVatCentavos: vat.lineVatCentavos,
      };
    }

    return {
      ...lineLevel,
      // Identity, carried through so an invoice line is traceable to a batch.
      orderItemId: null,
      inventoryId: typeof it.inventoryId === "string" ? it.inventoryId : null,
      batchId: typeof it.batchId === "string" ? it.batchId : "",
      vaccineName: typeof it.name === "string" ? it.name : "",
      itemDescription: typeof it.name === "string" ? it.name : "",
      expiry: "",
      quantity,
      unit: typeof order.unit === "string" && order.unit ? order.unit : "vials",
      unitPriceCentavos: it.unitPriceCentavos,
      lineTotalCentavos,
      // The order item's immutable VAT snapshot, or null on an order created
      // before snapshots existed. Never inferred from the product's current value.
      vatClassification: readProductVatClassification(it?.vatClassification),
      // Peso mirrors for the print template, derived — never authoritative.
      unitPrice: centavosToPesos(it.unitPriceCentavos),
      amount: centavosToPesos(lineTotalCentavos),
    };
  });

  if (!Number.isSafeInteger(subtotalCentavos)) {
    throw new PolicyError("order-snapshot-invalid", "This order's subtotal is out of range.");
  }
  // The order recorded its own subtotal at reservation time. If the two ever
  // disagree, something rewrote one of them and neither can be trusted.
  if (order.subtotalCentavos !== subtotalCentavos) {
    throw new PolicyError(
      "order-snapshot-invalid",
      "This order's subtotal does not match its line items."
    );
  }
  if (
    agreement &&
    (order.statutoryDiscountTotalCentavos !== statutoryDiscountTotalCentavos ||
      order.finalTotalCentavos !== subtotalCentavos - statutoryDiscountTotalCentavos)
  ) {
    throw new PolicyError(
      "order-snapshot-invalid",
      "This order's discount total or final total does not match its line items."
    );
  }
  // Every server-priced order has recorded its convention since pricing began
  // (the same commit stamped pricingVersion and priceIsVatInclusive). One
  // without it is damaged; guessing — from the current configuration or
  // anything else — would decide after the fact what the clinic was charged.
  const priceIsVatInclusive = readPriceConvention(order.priceIsVatInclusive);
  if (priceIsVatInclusive === null) {
    throw new PolicyError(
      "order-snapshot-invalid",
      "This order does not record whether its prices include VAT."
    );
  }

  // Agreement-model orders are invoiced at what each line is CHARGED. The
  // client's rule: the invoice shows no separate discount line. The statutory
  // discount stays in the order and its audit record; on the invoice each
  // line's amount is its final charged total, and every total below is built
  // from those amounts — so the visible lines add up to the visible totals.
  const invoiceItems = agreement ? items.map(finalChargedInvoiceLine) : items;
  const invoiceSubtotalCentavos = agreement
    ? subtotalCentavos - statutoryDiscountTotalCentavos
    : subtotalCentavos;

  return {
    items: invoiceItems,
    subtotalCentavos: invoiceSubtotalCentavos,
    subtotal: centavosToPesos(invoiceSubtotalCentavos),
    // Recorded on the order, carried onto the invoice rather than assumed.
    priceCurrency: typeof order.priceCurrency === "string" ? order.priceCurrency : PRICE_CURRENCY,
    // The ORDER's recorded convention, carried onto the invoice unchanged: a
    // new order's prices include VAT; a legacy order recorded VAT-exclusive is
    // invoiced VAT-exclusive. Never the current configuration.
    priceIsVatInclusive,
    pricingVersion: PRICING_VERSION,
    // True only when every line carries a VAT snapshot (orders created with
    // per-item classification). Partial snapshots are not itemized.
    itemizedVat: items.every((i) => i.vatClassification !== null),
    // Agreement-model orders: line amounts are final charged amounts and VAT
    // is per line, as recorded at placement. The invoice carries NO discount:
    // `recordedDiscountCentavos` is 0, which the adjustments must match.
    // Every other order keeps the Admin's own invoice discount (null).
    lineLevel: agreement,
    recordedDiscountCentavos: agreement ? 0 : null,
    finalTotalCentavos: agreement ? invoiceSubtotalCentavos : null,
  };
}

/**
 * One invoice line of an agreement-model order, presented at its FINAL charged
 * amount (`finalLineTotalCentavos`). The statutory discount is already inside
 * that amount and is not carried onto the invoice line.
 *
 * The unit price shown is the final amount ÷ quantity ONLY when that divides
 * exactly. A fixed line discount often does not; a rounded per-unit figure
 * would then be fabricated, and unit × quantity would not equal the amount. In
 * that case the unit price is null and the invoice shows the amount alone.
 */
function finalChargedInvoiceLine(line) {
  const amount = line.finalLineTotalCentavos;
  const exactUnit = amount % line.quantity === 0 ? amount / line.quantity : null;
  return {
    orderItemId: line.orderItemId,
    inventoryId: line.inventoryId,
    batchId: line.batchId,
    vaccineName: line.vaccineName,
    itemDescription: line.itemDescription,
    expiry: line.expiry,
    quantity: line.quantity,
    unit: line.unit,
    unitPriceCentavos: exactUnit,
    lineTotalCentavos: amount,
    // Says plainly that this amount is the net charged amount, after any
    // statutory discount — so a reader never infers it.
    amountIsFinalCharged: true,
    vatClassification: line.vatClassification,
    lineVatCentavos: line.lineVatCentavos,
    unitPrice: exactUnit === null ? null : centavosToPesos(exactUnit),
    amount: centavosToPesos(amount),
  };
}

/**
 * Split an invoice discount between VATable, VAT-Exempt and Zero-Rated sales
 * in proportion to their gross amounts, in whole centavos. Each share is
 * floored; the leftover centavos (at most one per bucket beyond the first) go
 * to the LARGEST bucket — VATable, then VAT-Exempt, then Zero-Rated on a tie.
 * With no zero-rated sales this is exactly the two-bucket split invoices have
 * always used. The shares always sum to the discount exactly. BigInt keeps
 * discount × gross exact however large the figures are.
 */
function allocateDiscountCentavos({ vatableGrossCentavos, vatExemptGrossCentavos, zeroRatedGrossCentavos = 0, discountCentavos }) {
  const total = vatableGrossCentavos + vatExemptGrossCentavos + zeroRatedGrossCentavos;
  if (discountCentavos === 0 || total === 0) return { vatableCentavos: 0, vatExemptCentavos: 0, zeroRatedCentavos: 0 };
  const d = BigInt(discountCentavos);
  const t = BigInt(total);
  const shares = [vatableGrossCentavos, vatExemptGrossCentavos, zeroRatedGrossCentavos].map((g) =>
    Number((d * BigInt(g)) / t)
  );
  const remainder = discountCentavos - shares[0] - shares[1] - shares[2];
  const grosses = [vatableGrossCentavos, vatExemptGrossCentavos, zeroRatedGrossCentavos];
  let largest = 0;
  for (let i = 1; i < 3; i += 1) if (grosses[i] > grosses[largest]) largest = i;
  shares[largest] += remainder;
  return { vatableCentavos: shares[0], vatExemptCentavos: shares[1], zeroRatedCentavos: shares[2] };
}

/**
 * The admin's explicit adjustments.
 *
 * These are the only money figures a caller may supply, and each one is its own
 * named field. None of them touches a unit price: a discount reduces the net,
 * it does not restate what a vial cost, and the base subtotal on the stored
 * invoice stays exactly what the order said.
 */
function validateAdjustments(raw, subtotalCentavos, { itemizedVat = false, recordedDiscountCentavos = null } = {}) {
  const input = raw && typeof raw === "object" && !Array.isArray(raw) ? raw : {};

  const allowed = ["discountCentavos", "otherChargesCentavos", "withholdingTaxCentavos", "vatClassification"];
  for (const key of Object.keys(input)) {
    if (!allowed.includes(key)) {
      throw new PolicyError("unknown-field", `Adjustments cannot carry "${key}".`);
    }
  }

  const read = (key) => {
    const value = input[key];
    if (value === undefined || value === null) return 0;
    if (!readCentavos(value)) {
      throw new PolicyError(
        "invalid-adjustment",
        "Discounts and charges must be whole centavos of zero or more."
      );
    }
    return value;
  };

  let discountCentavos = read("discountCentavos");

  // An agreement-model order recorded its statutory discounts PER LINE when it
  // was placed, and its invoice lines are already the final charged amounts —
  // the invoice carries no discount of its own (recorded: 0). A caller may
  // omit it or send that value — never change it.
  if (recordedDiscountCentavos !== null) {
    const sent = input.discountCentavos;
    if (sent !== undefined && sent !== null && sent !== recordedDiscountCentavos) {
      throw new PolicyError(
        "discount-recorded-per-line",
        "This order's SC/PWD discounts were recorded per line when it was placed and are already included in its line amounts. The invoice discount cannot be changed here.",
        { recordedDiscountCentavos }
      );
    }
    discountCentavos = recordedDiscountCentavos;
  }
  const otherChargesCentavos = read("otherChargesCentavos");
  const withholdingTaxCentavos = read("withholdingTaxCentavos");

  // A discount larger than the goods would invert the bill. Refused rather than
  // clamped: silently flooring it at the subtotal would charge an amount the
  // admin did not enter.
  if (discountCentavos > subtotalCentavos) {
    throw new PolicyError(
      "discount-exceeds-subtotal",
      "A discount cannot be larger than the invoice subtotal.",
      { discountCentavos, subtotalCentavos }
    );
  }

  // An itemized order's VAT is decided by its items; whatever the caller sent
  // for the invoice-level classification is ignored, never applied. An order
  // without item snapshots keeps the Admin's choice — which must be explicit:
  // VAT is never invented for an amount nobody marked VATable.
  const vatClassification = itemizedVat ? ITEMIZED_VAT : input.vatClassification;
  if (!itemizedVat && (vatClassification === undefined || vatClassification === null)) {
    throw new PolicyError(
      "vat-classification-required",
      "Choose this invoice's VAT classification. The order's products are not classified."
    );
  }
  if (!itemizedVat && !VAT_CLASSIFICATIONS.includes(vatClassification)) {
    throw new PolicyError("invalid-adjustment", "That VAT classification is not recognised.");
  }

  return { discountCentavos, otherChargesCentavos, withholdingTaxCentavos, vatClassification };
}

/**
 * Invoice totals, in centavos, under the record's OWN price convention.
 *
 * `priceIsVatInclusive` is REQUIRED and must be the stored flag of the order
 * (or receipt) being totalled — never the current configuration, which only
 * decides what a NEW record is stamped with. Anything but a boolean is refused.
 *
 * priceIsVatInclusive: true — the amount after any discount is VAT-inclusive.
 * For VATable sales the VAT is EXTRACTED — never added on top — so the total
 * stays exactly that amount (plus any other charges):
 *
 *   grossAfterDiscount = max(0, subtotal − discount)       (discount handling unchanged)
 *   VATable:  vat = round(grossAfterDiscount × 12 ÷ 112)    (half up, integers)
 *             net = grossAfterDiscount − vat                ("Amount: Net of VAT")
 *   exempt / zero-rated:  vat = 0, net = grossAfterDiscount
 *   grandTotal = net + vat + otherCharges  = grossAfterDiscount + otherCharges
 *
 * priceIsVatInclusive: false — LEGACY. The calculation those orders were
 * recorded under, preserved exactly: the amount after discount is net of VAT,
 * and 12% is added on top (Math.round, once on the aggregate):
 *
 *   net = max(0, subtotal − discount);  vat = round(VATable net × 12 ÷ 100)
 *   grandTotal = net + vat + otherCharges
 *
 * One rounding, on the aggregated VATable amount, in both conventions. Mirrors
 * computeInvoiceTotals in src/services/invoiceModel.js, which is used for the
 * editor's display and the manual path.
 */
function computeInvoiceTotalsCentavos({ subtotalCentavos, adjustments, items = [], priceIsVatInclusive, lineLevel = false }) {
  const { discountCentavos, otherChargesCentavos, withholdingTaxCentavos, vatClassification } =
    adjustments;
  const inclusive = readPriceConvention(priceIsVatInclusive);
  if (inclusive === null) {
    throw new PolicyError(
      "price-convention-required",
      "These totals need the record's own price convention (VAT-inclusive or VAT-exclusive)."
    );
  }

  let netCentavos;
  let vatRate;
  let vatAmountCentavos;
  let vatableSalesCentavos;
  let vatExemptSalesCentavos;
  let zeroRatedSalesCentavos;

  if (lineLevel) {
    // Agreement-model pricing: VAT is extracted from each line's FINAL total
    // (12/112, half up, per line). Nothing is allocated pro-rata. A line may
    // carry its statutory discount (an order receipt: gross − discount) or be
    // already final (an invoice: amount charged, no discount); either way the
    // `discountCentavos` here must be exactly the sum of the line discounts.
    if (!inclusive || vatClassification !== ITEMIZED_VAT) {
      throw new PolicyError("order-snapshot-invalid", "This order's per-line pricing cannot be invoiced this way.");
    }
    let lineDiscounts = 0;
    let lineSubtotal = 0;
    vatableSalesCentavos = 0;
    vatAmountCentavos = 0;
    vatExemptSalesCentavos = 0;
    zeroRatedSalesCentavos = 0;
    for (const it of items) {
      const cls = readProductVatClassification(it?.vatClassification);
      const gross = it?.lineTotalCentavos;
      const discount = it?.statutoryDiscountCentavos ?? 0;
      if (!cls || !readCentavos(gross) || !readCentavos(discount) || discount > gross) {
        throw new PolicyError("order-snapshot-invalid", "This order's line totals cannot be invoiced.");
      }
      const final = gross - discount;
      const vat = lineVat(final, cls);
      lineSubtotal += gross;
      lineDiscounts += discount;
      if (cls === "vatable") {
        vatableSalesCentavos += vat.lineNetOfVatCentavos;
        vatAmountCentavos += vat.lineVatCentavos;
      } else if (cls === "zero_rated") {
        zeroRatedSalesCentavos += final;
      } else {
        vatExemptSalesCentavos += final;
      }
    }
    if (lineSubtotal !== subtotalCentavos || lineDiscounts !== discountCentavos) {
      throw new PolicyError("order-snapshot-invalid", "This order's discounts do not match its line items.");
    }
    netCentavos = vatableSalesCentavos + vatExemptSalesCentavos + zeroRatedSalesCentavos;
    vatRate = vatAmountCentavos > 0 || vatableSalesCentavos > 0 ? VAT_STANDARD_RATE : 0;
  } else if (vatClassification === ITEMIZED_VAT) {
    // Per-item VAT: sum each bucket from the line snapshots, then split the
    // discount pro-rata. Every line must carry a valid snapshot.
    let vatableGrossCentavos = 0;
    let vatExemptGrossCentavos = 0;
    let zeroRatedGrossCentavos = 0;
    for (const it of items) {
      const cls = readProductVatClassification(it?.vatClassification);
      if (!cls || !readCentavos(it?.lineTotalCentavos)) {
        throw new PolicyError(
          "order-snapshot-invalid",
          "This order's VAT classifications cannot be invoiced."
        );
      }
      if (cls === "vatable") vatableGrossCentavos += it.lineTotalCentavos;
      else if (cls === "zero_rated") zeroRatedGrossCentavos += it.lineTotalCentavos;
      else vatExemptGrossCentavos += it.lineTotalCentavos;
    }
    if (vatableGrossCentavos + vatExemptGrossCentavos + zeroRatedGrossCentavos !== subtotalCentavos) {
      throw new PolicyError("order-snapshot-invalid", "This order's subtotal does not match its line items.");
    }
    const share = allocateDiscountCentavos({ vatableGrossCentavos, vatExemptGrossCentavos, zeroRatedGrossCentavos, discountCentavos });
    const vatableAfterDiscountCentavos = vatableGrossCentavos - share.vatableCentavos;
    if (inclusive) {
      // Both buckets are VAT-inclusive amounts. VAT is extracted from the
      // VATable bucket once, on its aggregate (one rounding per invoice).
      vatAmountCentavos = splitVatInclusiveCentavos(vatableAfterDiscountCentavos).vatCentavos;
      vatableSalesCentavos = vatableAfterDiscountCentavos - vatAmountCentavos; // net of VAT
    } else {
      // LEGACY: the buckets are net of VAT; 12% is added on top.
      vatableSalesCentavos = vatableAfterDiscountCentavos;
      vatAmountCentavos = legacyVatOnTopCentavos(vatableSalesCentavos);
    }
    vatExemptSalesCentavos = vatExemptGrossCentavos - share.vatExemptCentavos;
    // Zero-rated: VAT at 0%, reported as its own sales line.
    zeroRatedSalesCentavos = zeroRatedGrossCentavos - share.zeroRatedCentavos;
    netCentavos = vatableSalesCentavos + vatExemptSalesCentavos + zeroRatedSalesCentavos;
    vatRate = vatableAfterDiscountCentavos > 0 ? VAT_STANDARD_RATE : 0;
  } else {
    const afterDiscountCentavos = Math.max(0, subtotalCentavos - discountCentavos);
    vatRate = vatClassification === "vatable" ? VAT_STANDARD_RATE : 0;
    if (inclusive) {
      vatAmountCentavos =
        vatClassification === "vatable" ? splitVatInclusiveCentavos(afterDiscountCentavos).vatCentavos : 0;
      // The amount net of VAT (equal to the gross when no VAT applies).
      netCentavos = afterDiscountCentavos - vatAmountCentavos;
    } else {
      // LEGACY: the amount after discount IS the net; VAT goes on top.
      netCentavos = afterDiscountCentavos;
      vatAmountCentavos = vatClassification === "vatable" ? legacyVatOnTopCentavos(netCentavos) : 0;
    }
    vatableSalesCentavos = vatClassification === "vatable" ? netCentavos : 0;
    vatExemptSalesCentavos = vatClassification === "vat_exempt" ? netCentavos : 0;
    zeroRatedSalesCentavos = vatClassification === "zero_rated" ? netCentavos : 0;
  }

  const grandTotalCentavos = netCentavos + vatAmountCentavos + otherChargesCentavos;
  const totalSalesVatInclusiveCentavos = netCentavos + vatAmountCentavos;
  const totalAmountDueCentavos = grandTotalCentavos - withholdingTaxCentavos;

  for (const value of [grandTotalCentavos, totalAmountDueCentavos]) {
    if (!Number.isSafeInteger(value)) {
      throw new PolicyError(
        "invoice-total-out-of-range",
        "This invoice's total is too large to record accurately."
      );
    }
  }

  return {
    netCentavos,
    vatRate,
    vatableSalesCentavos,
    vatExemptSalesCentavos,
    zeroRatedSalesCentavos,
    vatAmountCentavos,
    grandTotalCentavos,
    totalSalesVatInclusiveCentavos,
    totalAmountDueCentavos,
  };
}

/** Presentation text: allowlisted, string-only, bounded. Never money. */
function validatePresentation(raw) {
  const input = raw && typeof raw === "object" && !Array.isArray(raw) ? raw : {};
  const out = {};
  for (const key of Object.keys(input)) {
    if (!PRESENTATION_FIELDS.includes(key)) {
      throw new PolicyError("unknown-field", `An invoice cannot carry "${key}" as presentation.`);
    }
    const value = input[key];
    if (value === undefined || value === null) continue;
    if (typeof value !== "string") {
      throw new PolicyError("invalid-presentation", `"${key}" must be text.`);
    }
    if (value.length > MAX_PRESENTATION_LENGTH) {
      throw new PolicyError("invalid-presentation", `"${key}" is too long.`);
    }
    out[key] = value;
  }
  for (const key of PRESENTATION_FIELDS) {
    if (!(key in out)) out[key] = "";
  }
  return out;
}

/**
 * Does a STORED invoice still carry the order's base pricing?
 *
 * Used at issue time, and as a tamper check on anything that reached the
 * document by another route. Compares only base pricing — adjustments are the
 * admin's and are expected to differ from one save to the next.
 */
function baseMatchesOrder(invoice, base) {
  const items = Array.isArray(invoice?.items) ? invoice.items : [];
  if (items.length !== base.items.length) return false;

  for (let i = 0; i < items.length; i += 1) {
    const stored = items[i];
    const expected = base.items[i];
    if (
      stored?.inventoryId !== expected.inventoryId ||
      stored?.quantity !== expected.quantity ||
      stored?.unitPriceCentavos !== expected.unitPriceCentavos ||
      stored?.lineTotalCentavos !== expected.lineTotalCentavos ||
      (stored?.vatClassification ?? null) !== (expected.vatClassification ?? null) ||
      (stored?.amountIsFinalCharged ?? false) !== (expected.amountIsFinalCharged ?? false) ||
      (stored?.lineVatCentavos ?? null) !== (expected.lineVatCentavos ?? null)
    ) {
      return false;
    }
  }

  return (
    invoice?.subtotalCentavos === base.subtotalCentavos &&
    invoice?.priceCurrency === base.priceCurrency &&
    invoice?.priceIsVatInclusive === base.priceIsVatInclusive &&
    invoice?.pricingVersion === base.pricingVersion
  );
}

