"use strict";

/**
 * Rider trips: who may be given orders, and when a Rider is free again.
 * Pure decisions only; the transactions are in riderDispatchOps.js.
 *
 * One server-owned document per Rider, `riderDispatchStates/{riderUid}`:
 *
 *   available_at_hub   at the distribution hub, nothing assigned
 *   trip_forming       orders assigned, not yet departed — more may JOIN
 *   on_trip            departed (Finalize Dispatch) — no new assignment
 *   returning_to_hub   every trip order settled — still no new assignment
 *                      until a Dispatcher/Admin confirms the physical return
 *
 *   available ─assign→ forming ─assign→ forming ─finalize→ on_trip
 *   forming ─(every member cancelled before departure)→ available
 *   on_trip ─(every member settled)→ returning ─confirm return→ available
 *                                    (or forming, if legacy held orders wait)
 *
 * The trip id is generated by the server (a `riderTrips` document id) and
 * stamped on each member order as `dispatchTripId`. It is unrelated to the
 * route optimizer's client-generated `tripId`, which stays a route field.
 *
 * The distribution hub is not a clinic. Nothing here reads a clinic, a
 * destination or a location: "returned" is a human confirmation, recorded with
 * who confirmed it.
 */

const { isoDateOnly } = require("./policy");

const RIDER_DISPATCH_STATES = "riderDispatchStates";
const RIDER_TRIPS = "riderTrips";

const STATE = Object.freeze({
  AVAILABLE: "available_at_hub",
  FORMING: "trip_forming",
  ON_TRIP: "on_trip",
  RETURNING: "returning_to_hub",
});
const STATES = Object.freeze(Object.values(STATE));

/** Assigned to the Rider, not yet left the hub. */
const PRE_DEPARTURE = Object.freeze(["assigned", "loading"]);
/** On the road with the Rider. */
const DEPARTED = Object.freeze(["in_transit", "delayed"]);
/**
 * No longer being carried to a destination. `delivery_failed` is not a
 * terminal LIFECYCLE status (a Dispatcher still requeues or cancels it), but
 * for the trip it is finished: the Rider stopped, and its vials ride back to
 * the hub with them, which is exactly what the return confirmation records.
 */
const SETTLED = Object.freeze(["delivered", "cancelled", "delivery_failed"]);

const isText = (v) => typeof v === "string" && v.length > 0;
const sortedUnique = (ids) => [...new Set(ids.filter(isText))].sort();

/**
 * Is this order finished as far as THIS trip is concerned? Settled statuses,
 * and also an order that left the trip (requeued → unassigned, or now with
 * another Rider/trip) or no longer exists.
 */
function settledForTrip(order, riderUid, tripId) {
  if (!order) return true;
  if (order.assignedRiderId !== riderUid) return true;
  if (isText(order.dispatchTripId) && order.dispatchTripId !== tripId) return true;
  return SETTLED.includes(order.status);
}

const MISSING_DATE_MESSAGE = "This order needs a delivery date before it can be dispatched.";
const INVALID_DATE_MESSAGE = "This order has an invalid delivery date and cannot be dispatched.";

function formatScheduledDate(iso) {
  return new Date(`${iso}T00:00:00.000Z`).toLocaleDateString("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
    timeZone: "UTC",
  });
}

/**
 * Same decision, codes and wording as the web's dispatchEligibility
 * (src/services/dispatchEligibility.js — parity-tested), and the same instant
 * as firestore.rules scheduleAllowsDispatch: a stored `requestedDeliveryDate`
 * that IS a canonical real date, and now ≥ 00:00 Manila on it.
 */
function scheduleEligibility(order, now) {
  if (order == null || !Object.prototype.hasOwnProperty.call(order, "requestedDeliveryDate") || order.requestedDeliveryDate === undefined) {
    return { eligible: false, code: "scheduled-date-missing", message: MISSING_DATE_MESSAGE };
  }
  const raw = order.requestedDeliveryDate;
  const iso = typeof raw === "string" ? isoDateOnly(raw) : null;
  if (iso === null || iso !== raw) {
    return { eligible: false, code: "scheduled-date-invalid", message: INVALID_DATE_MESSAGE };
  }
  if (now.getTime() < Date.parse(`${iso}T00:00:00.000Z`) - 8 * 3600 * 1000) {
    return {
      eligible: false,
      code: "scheduled-date-not-reached",
      message: `This order is scheduled for ${formatScheduledDate(iso)} and cannot be dispatched yet.`,
    };
  }
  return { eligible: true };
}

const scheduleReached = (order, now) => scheduleEligibility(order, now).eligible;

/** Same as firestore.rules orderIsFullyReserved: no partial dispatch. */
function fullyReserved(order) {
  return order?.allocationVersion !== 2 || order?.allocationState === "fully_reserved";
}

/** Why this order cannot be assigned or dispatched now, else null. */
function dispatchBlock(order, now) {
  const schedule = scheduleEligibility(order, now);
  if (!schedule.eligible) return { code: schedule.code, message: schedule.message };
  if (!fullyReserved(order)) {
    return {
      code: "order-not-fully-reserved",
      message: "This order is still waiting for stock. It can be assigned once every item is fully reserved.",
    };
  }
  return null;
}

/**
 * Derive a Rider's state from their orders, for a Rider with no state document
 * yet (everyone, at rollout) — never frees a Rider who is on the road.
 *
 *   any in_transit / delayed order  → on_trip; those orders are the trip, and
 *                                     any assigned/loading orders (given while
 *                                     already out, which the old model allowed)
 *                                     are HELD for the next trip
 *   only assigned / loading         → trip_forming with those orders
 *   none                            → available_at_hub
 *
 * `orders`: [{ id, data }] currently assigned to the Rider.
 */
function classifyFromOrders(orders) {
  const departed = [];
  const pre = [];
  for (const { id, data } of orders) {
    if (DEPARTED.includes(data?.status)) departed.push(id);
    else if (PRE_DEPARTURE.includes(data?.status)) pre.push(id);
  }
  if (departed.length > 0) {
    return { state: STATE.ON_TRIP, orderIds: sortedUnique(departed), heldOrderIds: sortedUnique(pre) };
  }
  if (pre.length > 0) return { state: STATE.FORMING, orderIds: sortedUnique(pre), heldOrderIds: [] };
  return { state: STATE.AVAILABLE, orderIds: [], heldOrderIds: [] };
}

/**
 * The next state after any order change — the one rule the order-write
 * trigger applies, and the one a missing state document is classified with.
 *
 * Inputs:
 *   current     the stored state (null → classify)
 *   memberOrders Map id → order data (or null) for current.orderIds + heldOrderIds
 *   riderOrders  [{ id, data }] currently assigned to the Rider (by query)
 *
 * Output: { state, orderIds, heldOrderIds, adoptOrderIds, departedByLegacyWrite,
 *           dissolved, settled, anomalies } — or { unchanged: true }.
 *
 * Orders assigned WITHOUT the server (a direct client write during the
 * rollout window, before the rules forbid it) are folded in, never rejected
 * after the fact: before departure they join the forming trip; once the
 * Rider is out they are held for the next trip and reported as anomalies.
 */
function reconcile({ riderUid, current, memberOrders, riderOrders }) {
  if (!current) {
    const c = classifyFromOrders(riderOrders);
    // Every trip member carries the server trip id; held orders get one when
    // their own trip forms.
    return { ...c, adoptOrderIds: c.orderIds, classified: true, anomalies: [] };
  }
  const tripId = current.tripId ?? null;
  const members = Array.isArray(current.orderIds) ? current.orderIds : [];
  const held = Array.isArray(current.heldOrderIds) ? current.heldOrderIds : [];
  const known = new Set([...members, ...held]);
  // Assigned to this Rider by a write that did not go through the server.
  const strays = riderOrders.filter(
    ({ id, data }) => !known.has(id) && !isText(data?.dispatchTripId) && [...PRE_DEPARTURE, ...DEPARTED].includes(data?.status)
  );
  const live = (id) => {
    const o = memberOrders.get(id);
    return o && o.assignedRiderId === riderUid && (!isText(o.dispatchTripId) || o.dispatchTripId === tripId);
  };
  const liveHeld = held.filter((id) => {
    const o = memberOrders.get(id);
    return o && o.assignedRiderId === riderUid && PRE_DEPARTURE.includes(o.status);
  });

  if (current.state === STATE.AVAILABLE) {
    if (strays.length === 0) return { unchanged: true };
    const c = classifyFromOrders(strays);
    return {
      ...c,
      adoptOrderIds: c.orderIds,
      departedByLegacyWrite: c.state === STATE.ON_TRIP,
      anomalies: strays.map((s) => s.id),
    };
  }

  if (current.state === STATE.FORMING) {
    const statusOf = (id) => (memberOrders.get(id) ?? strays.find((s) => s.id === id)?.data)?.status;
    const stillIn = members.filter((id) => live(id) && [...PRE_DEPARTURE, ...DEPARTED].includes(memberOrders.get(id).status));
    const strayIds = strays.map((s) => s.id);
    const all = sortedUnique([...stillIn, ...strayIds]);
    if (all.length === 0) {
      return { state: STATE.AVAILABLE, orderIds: [], heldOrderIds: [], adoptOrderIds: [], dissolved: true, anomalies: [] };
    }
    // A legacy client Finalize (rollout window) put members on the road. The
    // departed ones are the trip; any left behind wait for the next trip.
    const departed = all.filter((id) => DEPARTED.includes(statusOf(id)));
    if (departed.length > 0) {
      return {
        state: STATE.ON_TRIP,
        orderIds: departed,
        heldOrderIds: all.filter((id) => !departed.includes(id)),
        adoptOrderIds: departed.filter((id) => strayIds.includes(id)),
        departedByLegacyWrite: true,
        anomalies: strayIds,
      };
    }
    if (sameIds(all, members) && strayIds.length === 0) return { unchanged: true };
    return { state: STATE.FORMING, orderIds: all, heldOrderIds: [], adoptOrderIds: strayIds, anomalies: strayIds };
  }

  // on_trip / returning_to_hub: membership is frozen at departure. The only
  // way it grows is an order put on the road WITHOUT the server (a legacy
  // client Finalize during the rollout window) — then it joins this trip, so
  // a Rider carrying it can never be released.
  const preStrays = strays.filter((s) => PRE_DEPARTURE.includes(s.data.status)).map((s) => s.id);
  const dataOf = (id) => memberOrders.get(id) ?? strays.find((s) => s.id === id)?.data ?? null;
  const departedExtra = [...held, ...strays.map((s) => s.id)].filter((id) => {
    const o = dataOf(id);
    return o && o.assignedRiderId === riderUid && DEPARTED.includes(o.status);
  });
  const nextMembers = sortedUnique([...members, ...departedExtra]);
  const nextHeld = sortedUnique([...liveHeld, ...preStrays]);
  // An order joining now is judged as a member of THIS trip (it is stamped
  // with this trip id in the same write), whatever trip id it carried before.
  const asMember = (id) => {
    const o = dataOf(id);
    return o && departedExtra.includes(id) ? { ...o, dispatchTripId: tripId } : o;
  };
  const allSettled = nextMembers.every((id) => settledForTrip(asMember(id), riderUid, tripId));
  const nextState = allSettled
    ? (current.state === STATE.ON_TRIP ? STATE.RETURNING : current.state)
    : STATE.ON_TRIP;
  if (nextState === current.state && sameIds(nextHeld, held) && sameIds(nextMembers, members)) return { unchanged: true };
  const adopt = departedExtra.filter((id) => !isText(dataOf(id)?.dispatchTripId) || dataOf(id).dispatchTripId !== tripId);
  return {
    state: nextState,
    orderIds: nextMembers,
    heldOrderIds: nextHeld,
    adoptOrderIds: adopt,
    settled: nextState === STATE.RETURNING && current.state === STATE.ON_TRIP,
    departedByLegacyWrite: departedExtra.length > 0,
    anomalies: sortedUnique([...preStrays, ...departedExtra]),
  };
}

function sameIds(a, b) {
  const x = sortedUnique(a);
  const y = sortedUnique(b);
  return x.length === y.length && x.every((v, i) => v === y[i]);
}

/** May an order be ASSIGNED to a Rider in this state? (joining before departure only) */
function assignmentAllowed(state) {
  if (state === STATE.AVAILABLE || state === STATE.FORMING) return { ok: true };
  if (state === STATE.ON_TRIP) {
    return { ok: false, code: "rider-on-trip", message: "This rider has already left on a trip. New orders can be assigned after they return to the hub." };
  }
  if (state === STATE.RETURNING) {
    return { ok: false, code: "rider-returning", message: "This rider is returning to the hub. Confirm their return before assigning new orders." };
  }
  return { ok: false, code: "rider-state-unknown", message: "This rider's trip status could not be confirmed. Refresh and try again." };
}

